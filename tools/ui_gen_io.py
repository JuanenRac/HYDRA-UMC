"""The vectors the C twins of the PIN store and of the Jetson link are tested against, written from the Python references (tools/ui_pin.py, tools/ui_link.py).

`tools/ui_gen.py` calls `render_pin_vectors()` and `render_link_vectors()`; the files are `src/ui_h757/test/ui_pin_vectors.h` and `ui_link_vectors.h`. The PIN vectors hold hashes,
the bytes of the F-RAM after a PIN is set and the results of a list of attempts; the link vectors hold transcripts: for every step of the master the requests it sent, the answers
that came back and the events it reported. Evidence: simulator."""
from __future__ import annotations

import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ui_link as link  # noqa: E402
import ui_pin as pin  # noqa: E402

FAST = {"pin_hash_iterations": 1000, "pin_min_digits": 4, "pin_max_digits": 8}
SALT_A = bytes(range(16))
SALT_B = bytes(reversed(range(16)))
HEADER = [
    "/* =============================================================================",
    " * HYDRA-UMC Firmware - src/ui_h757/test/{name}",
    " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
    " * GPL-3.0-or-later - see LICENSE",
    " * ============================================================================= */",
    "/* Generated by tools/ui_gen_io.py from {source}. Do not edit: change the data and run tools/ui_gen.py. */",
]


def c_bytes(data: bytes) -> str:
    return "{" + ", ".join(f"0x{b:02x}" for b in data) + "}"


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_pin_vectors() -> str:
    hashes = [(b"4821", SALT_A, 1), (b"4821", SALT_A, 1000), (b"12345678", SALT_B, 7), (b"0000", SALT_A, 2), (b"12345678901234567890123456789012", SALT_B, 3)]
    lines = [line.format(name="ui_pin_vectors.h", source="tools/ui_pin.py") for line in HEADER]
    lines += ["#ifndef UI_PIN_VECTORS_H", "#define UI_PIN_VECTORS_H", "", "#include <stdint.h>", ""]
    lines += ["typedef struct { const char *pin; uint8_t salt[16]; uint32_t iterations; uint8_t hash[32]; } ui_vec_pbkdf2_t;", "static const ui_vec_pbkdf2_t ui_vec_pbkdf2[] = {"]
    for password, salt, iterations in hashes:
        lines.append(f"    {{{c_string(password.decode())}, {c_bytes(salt)}, {iterations}u, {c_bytes(pin._hash(password.decode(), salt, iterations))}}},")
    lines += ["};", f"#define UI_VEC_PBKDF2_COUNT {len(hashes)}", ""]

    # the bytes of the F-RAM after a PIN is set, and after another one is set over it
    fram = pin.Fram()
    store = pin.PinStore(fram, FAST)
    sets = []
    for password, salt in (("4821", SALT_A), ("9376", SALT_B)):
        store.set_pin(password, salt)
        sets.append((password, salt, bytes(fram.data)))
    lines += ["typedef struct { const char *pin; uint8_t salt[16]; uint8_t fram[144]; } ui_vec_set_t;", "static const ui_vec_set_t ui_vec_sets[] = {"]
    for password, salt, data in sets:
        lines.append(f"    {{{c_string(password)}, {c_bytes(salt)}, {c_bytes(data)}}},")
    lines += ["};", f"#define UI_VEC_SET_COUNT {len(sets)}", ""]

    # the results of a list of attempts on a store that holds "4821"
    attempts = ["0000", "4821", "12ab", "48210", "", "4821", "9999", "9998", "4821x", "4821"]
    fram = pin.Fram()
    store = pin.PinStore(fram, FAST)
    store.set_pin("4821", SALT_A)
    lines += ["typedef struct { const char *pin; uint8_t result; uint8_t failures; uint32_t fram_crc; } ui_vec_attempt_t;", "static const ui_vec_attempt_t ui_vec_attempts[] = {"]
    codes = {pin.OK: 0, pin.BAD: 1, pin.UNAVAILABLE: 2}
    for attempt in attempts:
        result = store.verify(attempt)
        lines.append(f"    {{{c_string(attempt)}, {codes[result]}, {store.failures()}, 0x{zlib.crc32(bytes(fram.data)) & 0xFFFFFFFF:08x}u}},")
    lines += ["};", f"#define UI_VEC_ATTEMPT_COUNT {len(attempts)}", "", "#endif /* UI_PIN_VECTORS_H */", ""]
    return "\n".join(lines)


class Recorder:
    """Wraps a Jetson double and records every request and answer. `damage_once_at`: the number of the snapshot answer to damage (one bit), `switch_picture_at`: after which snapshot
    answer a newer picture appears on the Jetson."""

    def __init__(self, host: link.FakeJetson, damage_once_at: int | None = None, switch_picture_at: int | None = None) -> None:
        self.host, self.damage_once_at, self.switch_picture_at = host, damage_once_at, switch_picture_at
        self.log: list[tuple[int, bytes, bytes | None]] = []
        self.snapshots = 0

    def answer(self, request: bytes, now_ms: int) -> bytes | None:
        answer = self.host.answer(request, now_ms)
        if answer is not None and request[1] == link.T_SNAPSHOT_REQ:
            self.snapshots += 1
            if self.damage_once_at == self.snapshots:
                answer = answer[:8] + bytes([answer[8] ^ 0x01]) + answer[9:]
            if self.switch_picture_at == self.snapshots:
                self.host.next_picture(link.make_jpeg(900, 5))
        self.log.append((now_ms, request, answer))
        return answer


def link_scenarios() -> list[dict]:
    def good():
        return Recorder(link.FakeJetson(link.make_jpeg(700, 1), zone_level=1)), {}

    def newer():
        host = link.FakeJetson(link.make_jpeg(700, 1))
        return Recorder(host), {700: lambda h: h.next_picture(link.make_jpeg(800, 2))}

    def silent():
        return Recorder(link.FakeJetson(link.make_jpeg(700, 1))), {300: lambda h: setattr(h, "mode", "silent"), 900: lambda h: setattr(h, "mode", "ok")}

    def corrupt():
        host = link.FakeJetson(link.make_jpeg(700, 1))
        host.mode = "corrupt"
        return Recorder(host), {}

    def hang():
        host = link.FakeJetson(link.make_jpeg(1000, 1))
        host.mode = "hang_in_picture"
        return Recorder(host), {}

    def damaged_chunk():
        return Recorder(link.FakeJetson(link.make_jpeg(900, 3)), damage_once_at=2), {}

    def switched_picture():
        return Recorder(link.FakeJetson(link.make_jpeg(900, 3)), switch_picture_at=1), {}

    return [
        {"name": "good", "make": good, "seconds": 1500},
        {"name": "newer_picture", "make": newer, "seconds": 1800},
        {"name": "silent_then_back", "make": silent, "seconds": 1500},
        {"name": "corrupt", "make": corrupt, "seconds": 1000},
        {"name": "hang_in_picture", "make": hang, "seconds": 1000},
        {"name": "damaged_chunk", "make": damaged_chunk, "seconds": 1500},
        {"name": "picture_changes_mid_transfer", "make": switched_picture, "seconds": 1500},
    ]


def render_link_vectors() -> str:
    pool = bytearray()
    lines = [line.format(name="ui_link_vectors.h", source="tools/ui_link.py") for line in HEADER]
    lines += ["#ifndef UI_LINK_VECTORS_H", "#define UI_LINK_VECTORS_H", "", "#include <stdint.h>", ""]
    body: list[str] = []
    table: list[str] = []
    for index, scenario in enumerate(link_scenarios()):
        recorder, actions = scenario["make"]()
        host = recorder.host
        master = link.LinkMaster(recorder, 2 * 1024)  # type: ignore[arg-type]
        transactions: list[str] = []
        steps: list[str] = []
        done_before = 0
        for now in range(0, scenario["seconds"], 50):
            if now in actions:
                actions[now](host)
            first = len(recorder.log)
            events = master.step(now)
            used = recorder.log[first:]
            for stamp, request, answer in used:
                request_offset = len(pool)
                pool += request
                answer_offset = len(pool)
                if answer is not None:
                    pool += answer
                transactions.append(f"    {{{stamp}u, {request_offset}u, {len(request)}u, {len(answer) if answer is not None else -1}, {answer_offset}u}},")
            kinds = {"HB": 0, "SPI_OK": 1, "SPI_ERR": 2}
            event_text = ", ".join(f"{{{kinds[name]}, {args[0] if args else 0}}}" for name, args in events) or "{0, 0}"
            picture = master.pictures[-1] if len(master.pictures) > done_before else b""
            crc = zlib.crc32(picture) & 0xFFFFFFFF if picture else 0
            steps.append(f"    {{{now}u, {first - 0}u, {len(used)}u, {len(events)}u, {{{event_text}}}, {len(master.pictures)}u, {len(picture)}u, 0x{crc:08x}u, {master.assembler.dropped}u}},")
            done_before = len(master.pictures)
            # the index of the first transaction of the step counts from the start of THIS scenario
        body += [f"static const ui_vec_txn_t ui_link_txns_{index}[] = {{"] + transactions + ["};", f"static const ui_vec_step_t ui_link_steps_{index}[] = {{"] + steps + ["};", ""]
        table.append(f"    {{{c_string(scenario['name'])}, {len(steps)}u, ui_link_steps_{index}, ui_link_txns_{index}, {2 * 1024}u}},")
    lines += [
        "typedef struct { uint64_t now; uint32_t request_offset; uint32_t request_length; int32_t answer_length; uint32_t answer_offset; } ui_vec_txn_t;",
        "typedef struct { uint8_t kind; uint8_t zone; } ui_vec_event_t;",
        "typedef struct {",
        "    uint64_t now; uint32_t first_txn; uint32_t txn_count; uint32_t event_count; ui_vec_event_t events[2];",
        "    uint32_t pictures_done; uint32_t picture_length; uint32_t picture_crc; uint32_t dropped;",
        "} ui_vec_step_t;",
        "typedef struct { const char *name; unsigned steps; const ui_vec_step_t *step; const ui_vec_txn_t *txn; uint32_t capacity; } ui_vec_link_scenario_t;",
        "",
        "/* Every request and answer of every scenario, one after the other; the transactions point into it. */",
        "static const uint8_t ui_link_pool[] = {",
    ]
    for start in range(0, len(pool), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in pool[start : start + 24]) + ",")
    lines += ["};", ""] + body
    lines += [f"#define UI_VEC_LINK_SCENARIOS {len(table)}", "static const ui_vec_link_scenario_t ui_vec_link_scenarios[UI_VEC_LINK_SCENARIOS] = {"] + table + ["};", "", "#endif /* UI_LINK_VECTORS_H */", ""]
    return "\n".join(lines)
