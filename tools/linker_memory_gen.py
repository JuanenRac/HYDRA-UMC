"""Writes the MEMORY block of the application linker scripts from the memory map of docs/platform_profiles.json, so the numbers of a region live in one place.

    python tools/linker_memory_gen.py            write the blocks
    python tools/linker_memory_gen.py --check    exit 1 when a linker script is not what the profile says

Each script carries its block between a BEGIN and an END line; the lines say which profile and core it was made from. The application scripts of the default platform are made from
`h745_current` and give the same regions as before (384 KB of flash for each core), so the default images do not change. `STM32H757XIHx_CM7_APP_768K.ld` is the script of the H757 slot of
768 KB (the end of bank 1, `h757_target`); it is made from the default script of the CM7 with that block and is not built by default: with it the copy of the application cannot be
the second half of the bank, and lives in the NOR flash instead (docs/H757_MEMORY_MAP.md, src/mcu_stm32h757/Common/nor_backup_plan.h). Evidence: simulator."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import platform_profile as pp

ROOT = Path(__file__).resolve().parents[1]
H7 = ROOT / "src" / "mcu_stm32h757"
# (script, profile, core, script it is derived from when it is not a file of its own)
TARGETS = (
    (H7 / "CM7" / "STM32H757XIHx_CM7_APP.ld", "h745_current", "CM7", None),
    (H7 / "CM4" / "STM32H757XIHx_CM4_APP.ld", "h745_current", "CM4", None),
    (H7 / "CM7" / "STM32H757XIHx_CM7_APP_768K.ld", "h757_target", "CM7", H7 / "CM7" / "STM32H757XIHx_CM7_APP.ld"),
)
BLOCK = re.compile(r"/\* MEMORY-BEGIN [^\r\n]*\*/(\r?\n)MEMORY.*?\}(\r?\n)/\* MEMORY-END \*/", re.S)


def block(profile: str, core: str, document: dict | None = None) -> str:
    return f"/* MEMORY-BEGIN generated by tools/linker_memory_gen.py from the profile {profile}, core {core} */\n{pp.linker_memory(profile, core, document)}\n/* MEMORY-END */"


def render(target: tuple, document: dict | None = None) -> str:
    """The text a script must have: the text of its source with the block of its profile (the line endings of the source are kept)."""
    path, profile, core, derived_from = target
    source = (derived_from or path).read_bytes().decode("utf-8")
    match = BLOCK.search(source)
    if match is None:
        raise ValueError(f"{(derived_from or path).name}: no MEMORY-BEGIN / MEMORY-END block")
    newline = "\r\n" if "\r\n" in source else "\n"
    return source[: match.start()] + block(profile, core, document).replace("\n", newline) + source[match.end() :]


def problems(document: dict | None = None) -> list[str]:
    found: list[str] = []
    for target in TARGETS:
        path = target[0]
        if not path.is_file():
            found.append(f"{path.name}: missing (run tools/linker_memory_gen.py)")
        elif path.read_bytes().decode("utf-8") != render(target, document):
            found.append(f"{path.name}: its MEMORY block is not what the profile {target[1]} says (run tools/linker_memory_gen.py)")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a script is not what the profile says")
    args = parser.parse_args(argv)
    bad = problems()
    if args.check:
        for line in bad:
            print("PROBLEM " + line, file=sys.stderr)
        print("LINKER_MEMORY=" + ("FAIL" if bad else "PASS"))
        return 1 if bad else 0
    for target in TARGETS:
        target[0].write_bytes(render(target).encode("utf-8"))
        print("wrote " + target[0].name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
