"""Writes tests/sdram_plan_golden.h: the start-up sequence of the SDRAM as tools/sdram_plan.py plans it for the default profile.

    python tools/gen_sdram_golden.py           write the file
    python tools/gen_sdram_golden.py --check   exit 1 when the file is not what the model produces

The C header src/mcu_stm32h757/Common/sdram_init.h runs the same sequence and tests/test_sdram_init.c compares every register write with these steps, so the firmware
and the model cannot drift apart. Evidence: simulator."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import platform_profile as pp
import sdram_plan as plan

HEADER_PATH = Path(__file__).resolve().parents[1] / "tests" / "sdram_plan_golden.h"
REGISTERS = {"SDCR1": 0, "SDTR1": 1, "SDCR2": 2, "SDTR2": 3, "SDCMR": 4, "SDRTR": 5}


def render() -> str:
    steps = plan.sequence(pp.profile("h757_target"))
    out = [
        "/* GENERATED by tools/gen_sdram_golden.py from tools/sdram_plan.py - do not edit by hand. */",
        "#ifndef HYDRA_SDRAM_PLAN_GOLDEN_H",
        "#define HYDRA_SDRAM_PLAN_GOLDEN_H",
        "",
        "typedef struct { int is_wait; int reg; unsigned long value; } SdramGoldenStep;",
        "static const SdramGoldenStep SDRAM_GOLDEN[] = {",
    ]
    for step in steps:
        if step["op"] == "write":
            out.append(f'    {{0, {REGISTERS[step["reg"]]}, {step["value"]}UL}}, /* {step["reg"]} */')
        else:
            out.append(f'    {{1, 0, {step["value"]}UL}}, /* wait in microseconds */')
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = HEADER_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n") if HEADER_PATH.is_file() else ""
        if current != text:
            print("SDRAM_GOLDEN=FAIL tests/sdram_plan_golden.h is not what the model produces: run tools/gen_sdram_golden.py", file=sys.stderr)
            return 1
        print("SDRAM_GOLDEN=PASS")
        return 0
    HEADER_PATH.write_bytes(text.encode("utf-8"))
    print(f"wrote {HEADER_PATH}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    raise SystemExit(main())
