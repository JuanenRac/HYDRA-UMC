"""Writes tests/zones_frame_vectors.h: scenarios for the filter of the brain on identifier 0x002, run through the Python reference (tools/zones_frame.py) so that the C twin
(src/mcu_stm32h757/CM4/zones_frame.h) is held to the same answers.

    python tools/gen_zones_vectors.py           write the header
    python tools/gen_zones_vectors.py --check   exit 1 when the header is not what the reference says

Each step is a frame (identifier, bytes) or a tick, with the time, and the answer the reference gives (1 = the brain must trip with the reason safety-zone). Evidence: simulator."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import zones_frame as z  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
HEADER_PATH = ROOT / "tests" / "zones_frame_vectors.h"


def hb(seq: int) -> bytes:
    return z.frame(z.KIND_HEARTBEAT, seq)


def stop(seq: int = 1) -> bytes:
    return z.frame(z.KIND_STOP, seq, subject=3, breached=1)


def bad_crc(data: bytes) -> bytes:
    return data[:7] + bytes([data[7] ^ 0x01])


SCENARIOS = {
    "stop_request_and_a_wrong_identifier": [("F", 0, 2, stop()), ("F", 10, 3, stop()), ("F", 20, 0x600, stop())],
    "a_damaged_frame_can_only_stop": [("F", 0, 2, bad_crc(stop())), ("F", 5, 2, stop()[:7]), ("F", 6, 2, z.frame(z.KIND_STOP, 1, version=2)), ("F", 7, 2, hb(1)[:3] + b"\xff" * 5)],
    "heartbeats_then_silence_trips_once": [("F", 0, 2, hb(1)), ("T", 500, 0, b""), ("F", 600, 2, hb(2)), ("T", 1500, 0, b""), ("T", 1700, 0, b""), ("T", 1800, 0, b"")],
    "armed_again_by_the_next_heartbeat": [("F", 0, 2, hb(1)), ("T", 1200, 0, b""), ("F", 2000, 2, hb(2)), ("T", 2500, 0, b""), ("T", 3100, 0, b"")],
    "no_trip_before_the_first_heartbeat": [("T", 0, 0, b""), ("T", 5000, 0, b""), ("T", 100000, 0, b"")],
    "a_replayed_heartbeat_does_not_keep_it_alive": [("F", 0, 2, hb(5)), ("F", 800, 2, hb(5)), ("F", 900, 2, hb(4)), ("T", 1100, 0, b"")],
    "the_sequence_wraps": [("F", 0, 2, hb(65535)), ("F", 500, 2, hb(0)), ("F", 1000, 2, hb(65000)), ("T", 1400, 0, b""), ("T", 1600, 0, b"")],
    "an_unknown_kind_is_ignored_but_a_stop_after_it_is_not": [("F", 0, 2, z.frame(9, 1)), ("F", 10, 2, stop(2))],
    "the_clock_wraps": [("F", 0xFFFFFF00, 2, hb(1)), ("T", 0x100, 0, b""), ("T", 0x300, 0, b"")],
    "a_stop_after_heartbeats_still_trips_and_so_does_the_silence_after": [("F", 0, 2, hb(1)), ("F", 100, 2, stop(2)), ("T", 1200, 0, b"")],
}


def render() -> str:
    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - tests/zones_frame_vectors.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        "/* Generated by tools/gen_zones_vectors.py from tools/zones_frame.py. Do not edit: change the reference and run the tool. */",
        "#ifndef ZONES_FRAME_VECTORS_H",
        "#define ZONES_FRAME_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        "/* op: 'F' a frame arrives, 'T' a tick; expected: 1 when the brain must trip with the reason safety-zone */",
        "typedef struct { char op; uint32_t t; uint32_t id; uint8_t dlc; uint8_t data[8]; uint8_t expected; } zones_step_t;",
        "typedef struct { const char *name; unsigned count; const zones_step_t *steps; } zones_scenario_t;",
        "",
    ]
    names = []
    for index, (name, steps) in enumerate(SCENARIOS.items()):
        f = z.ZonesFilter()
        lines.append(f"static const zones_step_t zones_steps_{index}[] = {{")
        for op, t, can_id, data in steps:
            expected = int(f.on_frame(t, can_id, data)) if op == "F" else int(f.tick(t))
            padded = (data + bytes(8))[:8]
            lines.append(f"    {{'{op}', {t}u, 0x{can_id:x}u, {len(data)}, {{{', '.join(f'0x{b:02x}' for b in padded)}}}, {expected}}},")
        lines += ["};", ""]
        names.append(f'    {{"{name}", {len(steps)}u, zones_steps_{index}}},')
    lines += [f"#define ZONES_SCENARIO_COUNT {len(SCENARIOS)}", "static const zones_scenario_t zones_scenarios[ZONES_SCENARIO_COUNT] = {"] + names + ["};", "", "#endif /* ZONES_FRAME_VECTORS_H */", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = HEADER_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n") if HEADER_PATH.is_file() else None
        if current != text:
            print("STALE: tests/zones_frame_vectors.h is not what the reference says (run tools/gen_zones_vectors.py)")
            return 1
        return 0
    HEADER_PATH.write_bytes(text.encode("utf-8"))
    print("wrote tests/zones_frame_vectors.h")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
