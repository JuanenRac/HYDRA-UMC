"""Writes the C tables of the interface of the STM32H757 from the data files, so the firmware never holds a number or a text that is not in one of them.

    python tools/ui_gen.py           write the files
    python tools/ui_gen.py --check   exit 1 when a file is not what the data says

Files: src/ui_h757/core/ui_config.h (config/ui.cfg), src/ui_h757/core/ui_texts.h (src/ui_h757/spec/i18n.json, the eight languages), src/ui_h757/core/ui_screens.h (src/ui_h757/spec/ui_spec.json: the signals, the
actions and the widgets of every screen) and src/ui_h757/test/ui_core_vectors.h (src/ui_h757/spec/scenarios.json replayed through tools/ui_model.py: the input and the expected trace of
every step). Evidence: simulator; nothing here has run on a board."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ui_model as model  # noqa: E402
import ui_gen_io  # noqa: E402
import ui_spec  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
BANNER = "/* Generated by tools/ui_gen.py from {source}. Do not edit: change the data and run the tool. */\n"
KIND_NAMES = ("value", "led", "button", "toggle", "banner", "tab", "list", "image", "text")
SIGNAL_TYPES = ("bool", "int", "float", "enum", "list", "image")
SIGNAL_SOURCES = ("stack_bus", "jetson_spi", "brain", "local", "derived")
NO_SIGNAL, NO_ACTION, NO_TEXT = 255, 255, 65535


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ident(name: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in name).upper()


def render_config() -> str:
    cfg = model.load_config()
    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - src/ui_h757/core/ui_config.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        BANNER.format(source="config/ui.cfg").rstrip("\n"),
        "#ifndef UI_CONFIG_H",
        "#define UI_CONFIG_H",
        "",
        '#include "ui_core.h"',
        "",
        "static const ui_config_t UI_CONFIG_DEFAULT = {",
    ]
    lines += [f"    {cfg[name]}u, /* {name} */" for name in model.CONFIG_FIELDS]
    lines += ["};", "", "#endif /* UI_CONFIG_H */", ""]
    return "\n".join(lines)


def render_texts(i18n: dict) -> str:
    keys = list(i18n["keys"])
    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - src/ui_h757/core/ui_texts.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        BANNER.format(source="src/ui_h757/spec/i18n.json").rstrip("\n"),
        "#ifndef UI_TEXTS_H",
        "#define UI_TEXTS_H",
        "",
        "/* The languages, in the order of the second index of ui_texts. */",
        "enum { " + ", ".join(f"UI_LANG_{lang.upper()} = {index}" for index, lang in enumerate(ui_spec.LANGUAGES)) + ", UI_LANG_COUNT = 8 };",
        "",
        "typedef enum {",
    ]
    lines += [f"    UI_T_{ident(key)} = {index}," for index, key in enumerate(keys)]
    lines += [f"    UI_T_COUNT = {len(keys)}", "} ui_text_id_t;", "", "/* UTF-8 text of every key in every language; the arrays are in flash. */",
              "static const char *const ui_texts[UI_T_COUNT][UI_LANG_COUNT] = {"]
    for key in keys:
        entry = i18n["keys"][key]
        lines.append("    {" + ", ".join(c_string(entry[lang]) for lang in ui_spec.LANGUAGES) + "}, /* " + key + " */")
    lines += ["};", "", "#endif /* UI_TEXTS_H */", ""]
    return "\n".join(lines)


def render_screens(spec: dict, i18n: dict) -> str:
    text_index = {key: index for index, key in enumerate(i18n["keys"])}
    signal_index = {s["id"]: index for index, s in enumerate(spec["signals"])}
    action_index = {a["id"]: index for index, a in enumerate(spec["actions"])}

    def widget(w: dict) -> str:
        rect = w["rect"]
        flags = (1 if w.get("hold") else 0) | (2 if w.get("repeat") else 0)
        return ("    {%d, %d, %d, %d, UI_WK_%s, %d, %d, %d, %d, %d, %d, %d}, /* %s */" % (
            rect["x"], rect["y"], rect["w"], rect["h"], KIND_NAMES[KIND_NAMES.index(w["kind"])].upper(),
            signal_index.get(w.get("signal", ""), NO_SIGNAL), signal_index.get(w.get("value_signal", ""), NO_SIGNAL),
            action_index.get(w.get("action", ""), NO_ACTION), text_index.get(w.get("label_key", ""), NO_TEXT),
            text_index.get(w.get("hint_key", ""), NO_TEXT), text_index.get(w.get("unit_key", ""), NO_TEXT), flags, w["id"]))

    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - src/ui_h757/core/ui_screens.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        BANNER.format(source="src/ui_h757/spec/ui_spec.json").rstrip("\n"),
        "#ifndef UI_SCREENS_H",
        "#define UI_SCREENS_H",
        "",
        "#include <stdint.h>",
        '#include "ui_texts.h"',
        "",
        f"enum {{ UI_FRAME_WIDTH = {spec['display']['width']}, UI_FRAME_HEIGHT = {spec['display']['height']}, UI_MIN_TOUCH_PX = {spec['display']['min_touch_px']} }};",
        f"enum {{ UI_NO_SIGNAL = {NO_SIGNAL}, UI_NO_ACTION_ID = {NO_ACTION}, UI_NO_TEXT = {NO_TEXT} }};",
        "enum { UI_WF_HOLD = 1, UI_WF_REPEAT = 2 };",
        "",
        "typedef enum { " + ", ".join(f"UI_WK_{name.upper()}" for name in KIND_NAMES) + " } ui_widget_kind_t;",
        "",
        "/* The signals a widget is bound to, in the order of src/ui_h757/spec/ui_spec.json. */",
        "typedef enum {",
    ]
    lines += [f"    UI_SIG_{ident(s['id'])} = {index}," for index, s in enumerate(spec["signals"])]
    lines += [f"    UI_SIG_COUNT = {len(spec['signals'])}", "} ui_signal_id_t;", "",
              "typedef struct { uint8_t type; uint8_t source; uint8_t needs_jetson; uint16_t max_age_ms; } ui_signal_info_t;",
              "static const ui_signal_info_t ui_signals[UI_SIG_COUNT] = {"]
    for s in spec["signals"]:
        lines.append("    {%d, %d, %d, %d}, /* %s */" % (SIGNAL_TYPES.index(s["type"]), SIGNAL_SOURCES.index(s["source"]), int(s["needs_jetson"]), s["max_age_ms"], s["id"]))
    lines += ["};", "", "/* The actions, in the order of src/ui_h757/spec/ui_spec.json: the first twelve are the ui_action_t of ui_core.h, the rest open a screen. */", "typedef enum {"]
    lines += [f"    UI_ACTID_{ident(a['id'])} = {index}," for index, a in enumerate(spec["actions"])]
    lines += [f"    UI_ACTID_COUNT = {len(spec['actions'])}", "} ui_action_id_t;", "",
              "typedef struct { uint16_t x, y, w, h; uint8_t kind, signal, value_signal, action; uint16_t label, hint, unit; uint8_t flags; } ui_widget_t;",
              "typedef struct { uint16_t title; uint8_t needs_jetson; uint8_t count; const ui_widget_t *widgets; } ui_screen_t;", "",
              f"#define UI_GLOBAL_WIDGET_COUNT {len(spec['global_widgets'])}", "static const ui_widget_t ui_global_widgets[UI_GLOBAL_WIDGET_COUNT] = {"]
    lines += [widget(w) for w in spec["global_widgets"]]
    lines += ["};", ""]
    for screen in spec["screens"]:
        lines.append(f"static const ui_widget_t ui_widgets_{screen['id']}[{len(screen['widgets'])}] = {{")
        lines += [widget(w) for w in screen["widgets"]]
        lines += ["};", ""]
    lines += [f"#define UI_SCREEN_TABLE_COUNT {len(spec['screens'])}", "static const ui_screen_t ui_screens[UI_SCREEN_TABLE_COUNT] = {"]
    for screen in spec["screens"]:
        lines.append("    {%d, %d, %d, ui_widgets_%s}, /* %s */" % (text_index[screen["title_key"]], int(screen["needs_jetson"]), len(screen["widgets"]), screen["id"], screen["id"]))
    lines += ["};", "", "#endif /* UI_SCREENS_H */", ""]
    return "\n".join(lines)


def render_vectors() -> str:
    scenarios = json.loads((ROOT / "src" / "ui_h757" / "spec" / "scenarios.json").read_text(encoding="utf-8"))["scenarios"]
    base = model.load_config()
    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - src/ui_h757/test/ui_core_vectors.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        BANNER.format(source="src/ui_h757/spec/scenarios.json and tools/ui_model.py").rstrip("\n"),
        "#ifndef UI_CORE_VECTORS_H",
        "#define UI_CORE_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct { uint64_t t; const char *name; int32_t a, b, c; } ui_vector_event_t;",
        "typedef struct { const char *name; uint32_t cfg[@N@]; unsigned count; const ui_vector_event_t *events; const char *const *expected; } ui_vector_scenario_t;".replace("@N@", str(len(model.CONFIG_FIELDS))),
        "",
    ]
    names = []
    for index, scenario in enumerate(scenarios):
        events = [model.parse_event(text) for text in scenario["events"]]
        expected = model.run_scenario(scenario, base)
        cfg = dict(base)
        cfg.update(scenario.get("cfg", {}))
        lines.append(f"static const ui_vector_event_t ui_events_{index}[] = {{")
        for now, name, args in events:
            padded = list(args) + [0] * (3 - len(args))
            lines.append(f'    {{{now}u, "{name}", {padded[0]}, {padded[1]}, {padded[2]}}},')
        lines += ["};", f"static const char *const ui_expected_{index}[] = {{"]
        lines += [f"    {c_string(line)}," for line in expected]
        lines += ["};", ""]
        values = ", ".join(f"{cfg[name]}u" for name in model.CONFIG_FIELDS)
        names.append(f'    {{{c_string(scenario["name"])}, {{{values}}}, {len(events)}u, ui_events_{index}, ui_expected_{index}}},')
    lines += [f"#define UI_VECTOR_SCENARIO_COUNT {len(scenarios)}", "static const ui_vector_scenario_t ui_vector_scenarios[UI_VECTOR_SCENARIO_COUNT] = {"]
    lines += names
    lines += ["};", "", "#endif /* UI_CORE_VECTORS_H */", ""]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    spec, i18n = ui_spec.load_spec(), ui_spec.load_i18n()
    return {
        ROOT / "src" / "ui_h757" / "core" / "ui_config.h": render_config(),
        ROOT / "src" / "ui_h757" / "core" / "ui_texts.h": render_texts(i18n),
        ROOT / "src" / "ui_h757" / "core" / "ui_screens.h": render_screens(spec, i18n),
        ROOT / "src" / "ui_h757" / "test" / "ui_core_vectors.h": render_vectors(),
        ROOT / "src" / "ui_h757" / "test" / "ui_pin_vectors.h": ui_gen_io.render_pin_vectors(),
        ROOT / "src" / "ui_h757" / "test" / "ui_link_vectors.h": ui_gen_io.render_link_vectors(),
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args(argv)
    stale = 0
    for path, text in outputs().items():
        if options.check:
            current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.is_file() else None
            if current != text:
                print(f"STALE: {path.relative_to(ROOT).as_posix()} is not what the data says (run tools/ui_gen.py)")
                stale += 1
        else:
            path.write_bytes(text.encode("utf-8"))
            print("wrote", path.relative_to(ROOT).as_posix())
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
