"""Writes the vectors of the emergency stop and of the slot scan as C headers for the host tests of the firmware.

    python tools/gen_node_vectors.py          writes tests/estop_vectors.h and tests/slot_scan_vectors.h
    python tools/gen_node_vectors.py --check  exits 1 when a header is not what the JSON files give

The JSON files (tests/estop_vectors.json, tests/slot_scan_vectors.json) are the single list of cases: the Python references and the C
firmware headers are both tested against them, and these generated headers are how the C tests read them. Nothing is compiled here.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TESTS = ROOT / "tests"

HEADER = """/* Generated by tools/gen_node_vectors.py from {source}. Do not edit by hand: run the tool again. */
"""

ACTIONS = {"frame": 0, "tick": 1, "bus_off": 2, "enable": 3}
STATES = {"LATCHED": 0, "READY": 1}


def c_bytes(data: bytes, size: int = 8) -> str:
    padded = data + bytes(size - len(data))
    return "{" + ", ".join(f"0x{b:02x}" for b in padded) + "}"


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', "'") + '"'


def estop_header() -> str:
    data = json.loads((TESTS / "estop_vectors.json").read_text(encoding="utf-8"))
    out = [HEADER.format(source="tests/estop_vectors.json"), "#include <stdint.h>\n"]
    out.append("typedef struct { const char *name; uint8_t kind, detail, source, epoch; uint16_t seq; uint8_t data[8]; } EstopVectorFrame;")
    out.append("typedef struct { const char *name; uint8_t dlc; uint8_t data[16]; } EstopVectorMalformed;")
    out.append("typedef struct { uint32_t t; uint8_t action; uint8_t dlc; uint8_t data[16]; int8_t expect_state; int8_t expect_drivers; int8_t expect_accepted; } EstopVectorStep;")
    out.append("typedef struct { const char *name; unsigned first_step; unsigned steps; } EstopVectorScenario;\n")
    out.append(f"#define ESTOP_VECTOR_ALIVE_TIMEOUT_MS {data['alive_timeout_ms']}u\n")
    out.append("static const EstopVectorFrame estop_vector_frames[] = {")
    for f in data["frames"]:
        out.append(f"    {{{c_string(f['name'])}, {f['kind']}, {f['detail']}, {f['source']}, {f['epoch']}, {f['seq']}, {c_bytes(bytes.fromhex(f['data_hex']))}}},")
    out.append("};\n")
    out.append("static const EstopVectorMalformed estop_vector_malformed[] = {")
    for m in data["malformed"]:
        raw = bytes.fromhex(m["data_hex"])
        out.append(f"    {{{c_string(m['name'])}, {len(raw)}, {c_bytes(raw, 16)}}},")
    out.append("};\n")
    steps: list[str] = []
    scenarios: list[str] = []
    for scenario in data["scenarios"]:
        scenarios.append(f"    {{{c_string(scenario['name'])}, {len(steps)}, {len(scenario['steps'])}}},")
        for step in scenario["steps"]:
            if "frame" in step:
                action, raw = ACTIONS["frame"], bytes.fromhex(step["frame"])
            else:
                action, raw = ACTIONS[step["do"]], b""
            expect = step.get("expect", {})
            state = STATES[expect["state"]] if "state" in expect else -1
            drivers = int(expect["drivers_enabled"]) if "drivers_enabled" in expect else -1
            accepted = int(expect["accepted"]) if "accepted" in expect else -1
            steps.append(f"    {{{step['t']}u, {action}, {len(raw)}, {c_bytes(raw, 16)}, {state}, {drivers}, {accepted}}},")
    out.append("static const EstopVectorStep estop_vector_steps[] = {")
    out += steps
    out.append("};\n")
    out.append("static const EstopVectorScenario estop_vector_scenarios[] = {")
    out += scenarios
    out.append("};\n")
    out.append("#define ESTOP_VECTOR_ACTION_FRAME 0\n#define ESTOP_VECTOR_ACTION_TICK 1\n#define ESTOP_VECTOR_ACTION_BUS_OFF 2\n#define ESTOP_VECTOR_ACTION_ENABLE 3\n")
    return "\n".join(out)


def slot_scan_header() -> str:
    data = json.loads((TESTS / "slot_scan_vectors.json").read_text(encoding="utf-8"))
    out = [HEADER.format(source="tests/slot_scan_vectors.json"), "#include <stdint.h>\n"]
    out.append("typedef struct { const char *name; uint8_t scan_id; uint8_t data[8]; } SlotScanVectorProbe;")
    out.append("typedef struct { const char *name; uint8_t board_id, role, scan_id; uint32_t uid32; uint8_t data[8]; } SlotScanVectorReply;")
    out.append("typedef struct { const char *name; uint8_t dlc; uint8_t data[16]; } SlotScanVectorMalformed;")
    out.append("typedef struct { uint32_t uid32; uint32_t delay_ms; } SlotScanVectorDelay;\n")
    out.append("static const SlotScanVectorProbe slot_scan_vector_probes[] = {")
    for p in data["probes"]:
        out.append(f"    {{{c_string(p['name'])}, {p['scan_id']}, {c_bytes(bytes.fromhex(p['data_hex']))}}},")
    out.append("};\n")
    out.append("static const SlotScanVectorReply slot_scan_vector_replies[] = {")
    for r in data["replies"]:
        out.append(f"    {{{c_string(r['name'])}, {r['board_id']}, {r['role']}, {r['scan_id']}, {r['uid32']}u, {c_bytes(bytes.fromhex(r['data_hex']))}}},")
    out.append("};\n")
    out.append("static const SlotScanVectorMalformed slot_scan_vector_malformed[] = {")
    for m in data["malformed"]:
        raw = bytes.fromhex(m["data_hex"])
        out.append(f"    {{{c_string(m['name'])}, {len(raw)}, {c_bytes(raw, 16)}}},")
    out.append("};\n")
    out.append("static const SlotScanVectorDelay slot_scan_vector_delays[] = {")
    for d in data["delays"]:
        out.append(f"    {{{d['uid32']}u, {d['delay_ms']}u}},")
    out.append("};\n")
    return "\n".join(out)


OUTPUTS = {"estop_vectors.h": estop_header, "slot_scan_vectors.h": slot_scan_header}


def main(argv: list[str]) -> int:
    failures = 0
    for name, make in OUTPUTS.items():
        text = make()
        path = TESTS / name
        if "--check" in argv:
            current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.is_file() else ""
            if current != text:
                print(f"NODE_VECTORS=FAIL tests/{name} is not what the JSON gives: run python tools/gen_node_vectors.py")
                failures += 1
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote tests/{name}")
    if "--check" in argv and not failures:
        print("NODE_VECTORS=PASS")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
