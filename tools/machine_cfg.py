"""Read config/machine.cfg, check it and write the header the controller board firmware builds from.

    python tools/machine_cfg.py generate   # rewrite src/mcu_stm32g474/machine_config.h
    python tools/machine_cfg.py check      # exit 1 when the header is stale or the file is invalid

The firmware has no file system: the tuned values of the stop (category per axis, the pin and the polarity of the physical input, debounce
times) are kept in config/machine.cfg and compiled in through the generated header, never typed into the source.
Nothing here has run on a board.
"""
from __future__ import annotations

import configparser
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CFG_PATH = ROOT / "config" / "machine.cfg"
HEADER_PATH = ROOT / "src" / "mcu_stm32g474" / "machine_config.h"
AXES = 6
FREE_PINS = {("A", 7), ("A", 12), ("B", 4), ("C", 9)}


class ConfigError(ValueError):
    pass


def _int(section, key, low, high, default=None):
    raw = section.get(key, "").strip()
    if raw == "":
        if default is None:
            raise ConfigError(f"{key} is missing")
        return default
    try:
        value = int(raw, 10)
    except ValueError as exc:
        raise ConfigError(f"{key} must be a whole number, not {raw!r}") from exc
    if not low <= value <= high:
        raise ConfigError(f"{key} must be {low}..{high}, not {value}")
    return value


def load(path: Path = CFG_PATH) -> dict:
    parser = configparser.ConfigParser(inline_comment_prefixes=None)
    parser.read_string(path.read_text(encoding="utf-8"))
    for name in ("stop", "estop_input", "production"):
        if name not in parser:
            raise ConfigError(f"section [{name}] is missing")
    stop, inp, prod = parser["stop"], parser["estop_input"], parser["production"]
    default_category = _int(stop, "default_category", 0, 1)
    categories = [_int(stop, f"axis{n}_category", 0, 1, default_category) for n in range(1, AXES + 1)]
    cfg = {
        "stop_categories": categories,
        "stop_ramp_max_ms": _int(stop, "ramp_max_ms", 1, 2000),
        "input_enabled": _int(inp, "enabled", 0, 1),
        "input_port": inp.get("port", "").strip().upper(),
        "input_pin": _int(inp, "pin", 0, 15),
        "input_healthy_level": _int(inp, "healthy_level", 0, 1),
        "input_trip_debounce_ms": _int(inp, "trip_debounce_ms", 0, 1000),
        "input_clear_debounce_ms": _int(inp, "clear_debounce_ms", 0, 5000),
        "input_trip_repeat_ms": _int(inp, "trip_repeat_ms", 1, 1000),
        "rdp_level": _int(prod, "rdp_level", 0, 1),
    }
    if cfg["input_enabled"] and (cfg["input_port"], cfg["input_pin"]) not in FREE_PINS:
        raise ConfigError(f"P{cfg['input_port']}{cfg['input_pin']} is not one of the free pins {sorted(FREE_PINS)}")
    return cfg


def render(cfg: dict) -> str:
    mask = 0
    for index, category in enumerate(cfg["stop_categories"]):
        mask |= category << index
    lines = [
        "/* Generated by tools/machine_cfg.py from config/machine.cfg. Do not edit by hand: change the file and run the tool. */",
        "#ifndef MACHINE_CONFIG_H",
        "#define MACHINE_CONFIG_H",
        "",
        "/* Bit n-1 is set when axis n stops with category 1 (decelerate, cut at the latest after the ramp); clear means category 0, cut at once. */",
        f"#define MACHINE_STOP_CATEGORY1_MASK 0x{mask:02X}u",
        f"#define MACHINE_STOP_RAMP_MAX_MS {cfg['stop_ramp_max_ms']}u",
        "",
        "/* The physical emergency stop input (normally closed, fail safe). */",
        f"#define MACHINE_ESTOP_INPUT_ENABLED {cfg['input_enabled']}",
        f"#define MACHINE_ESTOP_INPUT_PORT '{cfg['input_port']}'",
        f"#define MACHINE_ESTOP_INPUT_PIN {cfg['input_pin']}u",
        f"#define MACHINE_ESTOP_INPUT_HEALTHY_LEVEL {cfg['input_healthy_level']}u",
        f"#define MACHINE_ESTOP_INPUT_TRIP_DEBOUNCE_MS {cfg['input_trip_debounce_ms']}u",
        f"#define MACHINE_ESTOP_INPUT_CLEAR_DEBOUNCE_MS {cfg['input_clear_debounce_ms']}u",
        f"#define MACHINE_ESTOP_INPUT_TRIP_REPEAT_MS {cfg['input_trip_repeat_ms']}u",
        "",
        "/* Read-out protection level of a production flash (0 = off). */",
        f"#define MACHINE_PRODUCTION_RDP_LEVEL {cfg['rdp_level']}u",
        "",
        "#endif /* MACHINE_CONFIG_H */",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    try:
        text = render(load())
    except ConfigError as exc:
        print(f"machine.cfg: {exc}")
        return 1
    if command == "generate":
        HEADER_PATH.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {HEADER_PATH.relative_to(ROOT)}")
        return 0
    if command == "check":
        current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else ""
        if current != text:
            print("machine_config.h is stale: run python tools/machine_cfg.py generate")
            return 1
        print("machine_config.h matches config/machine.cfg")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
