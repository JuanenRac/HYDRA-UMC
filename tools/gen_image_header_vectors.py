"""Writes tests/image_header_vectors.h: two signed images and a downgrade token as the host reference (tools/image_header.py) makes
them, as C arrays, so that the C code of the bootloader (src/*/boot/image_header.h, update_verify.h and the HMAC of
bootloader_crypto.c) is checked against bytes the reference produced instead of against itself. Run it again after changing the
reference; tests/test_image_header_vectors.py fails if the file is stale.

    python tools/gen_image_header_vectors.py          writes the file
    python tools/gen_image_header_vectors.py --check  exits 1 when the file is not what the reference makes

Image A is 0.2.3 (an update over an installed 0.2.2). Image B is 0.1.8 (older than the installed 0.2.2: it needs the downgrade token,
which is made for exactly B's tag, the pair 0.2.2 -> 0.1.8 and the session nonce).
"""
from __future__ import annotations

import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import image_header as ih  # noqa: E402

OUTPUT = Path(__file__).resolve().parent.parent / "tests" / "image_header_vectors.h"

# The values of the G474 bootloader (bootloader_common.h): THIS_HARDWARE_ID "G401", MAIN_APP_ADDR.
HW_ID = 0x47343031
LINK = 0x08009000
RAM_LO = 0x20000100
RAM_HI = 0x20018000
KEY = bytes(range(0x40, 0x60))  # a made-up 32-byte key; never the key of a real build
NONCE = bytes(range(16))
VERSION_A = (0, 2, 3)
VERSION_B = (0, 1, 8)
INSTALLED = (0, 2, 2)
IMAGE_SIZE = 512


def make_image(seed: int) -> bytes:
    body = bytes((i * seed + 3) & 0xFF for i in range(IMAGE_SIZE - 8))
    return struct.pack("<II", 0x20010000, LINK + 0x101) + body


def array(name: str, data: bytes, comment: str) -> str:
    lines = [f"/* {comment} */", f"static const uint8_t {name}[{len(data)}] = {{"]
    for start in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[start:start + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def signed(version: tuple[int, int, int], seed: int) -> tuple[ih.ImageHeader, bytes, bytes]:
    image = make_image(seed)
    header = ih.ImageHeader(
        hw_id=HW_ID, major=version[0], minor=version[1], patch=version[2], image_size=len(image), link_address=LINK,
        vector_sp=struct.unpack_from("<I", image, 0)[0], vector_reset=struct.unpack_from("<I", image, 4)[0],
        image_crc32=zlib.crc32(image) & 0xFFFFFFFF,
    )
    blob = ih.build_signed_image(header, image, KEY)
    return header, image, blob[-ih.TAG_SIZE:]


def render() -> str:
    header_a, image_a, tag_a = signed(VERSION_A, 7)
    header_b, image_b, tag_b = signed(VERSION_B, 11)
    token = ih.downgrade_token(KEY, NONCE, INSTALLED, VERSION_B, tag_b)
    message = b"hydra-umc-downgrade\x00" + NONCE + struct.pack("<3H3H", *INSTALLED, *VERSION_B) + tag_b
    parts = [
        "/* =============================================================================",
        " * HYDRA-UMC - tests/image_header_vectors.h  (GENERATED by tools/gen_image_header_vectors.py; do not edit)",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * =============================================================================",
        " * Two signed images and a downgrade token as the host reference (tools/image_header.py) makes them.",
        " * A is 0.2.3, an update over the installed 0.2.2. B is 0.1.8, older than that: it needs the token.",
        " */",
        "#ifndef IMAGE_HEADER_VECTORS_H",
        "#define IMAGE_HEADER_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define VEC_HW_ID          0x{HW_ID:08X}UL",
        f"#define VEC_LINK_ADDRESS   0x{LINK:08X}UL",
        f"#define VEC_RAM_LO         0x{RAM_LO:08X}UL",
        f"#define VEC_RAM_HI         0x{RAM_HI:08X}UL",
        f"#define VEC_INSTALLED_MAJOR {INSTALLED[0]}",
        f"#define VEC_INSTALLED_MINOR {INSTALLED[1]}",
        f"#define VEC_INSTALLED_PATCH {INSTALLED[2]}",
        f"#define VEC_IMAGE_SIZE     {len(image_a)}u",
        "",
        f"#define VEC_VERSION_MAJOR  {VERSION_A[0]}",
        f"#define VEC_VERSION_MINOR  {VERSION_A[1]}",
        f"#define VEC_VERSION_PATCH  {VERSION_A[2]}",
        f"#define VEC_IMAGE_CRC32    0x{zlib.crc32(image_a) & 0xFFFFFFFF:08X}UL",
        f"#define VEC_VECTOR_SP      0x{header_a.vector_sp:08X}UL",
        f"#define VEC_VECTOR_RESET   0x{header_a.vector_reset:08X}UL",
        "",
        f"#define VEC_B_VERSION_MAJOR {VERSION_B[0]}",
        f"#define VEC_B_VERSION_MINOR {VERSION_B[1]}",
        f"#define VEC_B_VERSION_PATCH {VERSION_B[2]}",
        f"#define VEC_B_IMAGE_CRC32  0x{zlib.crc32(image_b) & 0xFFFFFFFF:08X}UL",
        "",
        array("VEC_KEY", KEY, "the signing key of these vectors (made up)"),
        "",
        array("VEC_HEADER", header_a.pack(), "image A: the 64-byte header"),
        "",
        array("VEC_IMAGE", image_a, "image A: its first two words are VEC_VECTOR_SP and VEC_VECTOR_RESET"),
        "",
        array("VEC_TAG", tag_a, "image A: HMAC-SHA256 under VEC_KEY over VEC_HEADER || VEC_IMAGE"),
        "",
        array("VEC_B_HEADER", header_b.pack(), "image B: the 64-byte header"),
        "",
        array("VEC_B_IMAGE", image_b, "image B"),
        "",
        array("VEC_B_TAG", tag_b, "image B: HMAC-SHA256 under VEC_KEY over VEC_B_HEADER || VEC_B_IMAGE"),
        "",
        array("VEC_NONCE", NONCE, "the session nonce of the downgrade token"),
        "",
        array("VEC_DOWNGRADE_MESSAGE", message, "tag || nonce || installed || target || tag of image B: what the downgrade token is the HMAC of"),
        "",
        array("VEC_DOWNGRADE_TOKEN", token, "HMAC-SHA256 under VEC_KEY over VEC_DOWNGRADE_MESSAGE: 0.2.2 -> 0.1.8 with image B"),
        "",
        "#endif /* IMAGE_HEADER_VECTORS_H */",
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.is_file() else ""
        if current != text:
            print(f"{OUTPUT} is not what tools/image_header.py makes: run python tools/gen_image_header_vectors.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
