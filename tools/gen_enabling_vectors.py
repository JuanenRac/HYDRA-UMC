"""Writes tests/enabling_device_vectors.h: scenarios for the three-position enabling device run through the Python reference (tools/enabling_device.py), so that the C twin
(src/mcu_stm32h757/CM4/enabling_device.h) is held to the same states.

    python tools/gen_enabling_vectors.py           write the header
    python tools/gen_enabling_vectors.py --check   exit 1 when the header is not what the reference says

Each step is a time and the two channels, with the state and the answer of the reference after it. Evidence: simulator."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import enabling_device as e  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
HEADER_PATH = ROOT / "tests" / "enabling_device_vectors.h"

R, M, P = e.RELEASED, e.MIDDLE, e.PANIC


def run(steps):
    """steps: (dt_ms, a, b) -> list of (t, a, b)"""
    t, out = 1000, []
    for dt, a, b in steps:
        t += dt
        out.append((t, a, b))
    return out


SCENARIOS = {
    "released_then_middle_enables_after_the_debounce": run([(0, R, R), (10, R, R), (15, R, R), (5, R, M), (3, M, M), (10, M, M), (15, M, M)]),
    "held_in_the_middle_at_power_up_never_enables": run([(0, M, M), (30, M, M), (500, M, M)]),
    "panic_stops_and_the_way_back_through_the_middle_does_not_enable": run([(0, R, R), (30, R, R), (5, M, M), (30, M, M), (5, P, P), (5, M, M), (50, M, M), (50, M, M)]),
    "release_after_panic_arms_again": run([(0, P, P), (5, M, M), (60, M, M), (5, R, R), (10, R, R), (15, R, R), (5, M, M), (30, M, M)]),
    "leaving_the_middle_stops_at_once": run([(0, R, R), (30, R, R), (5, M, M), (30, M, M), (1, R, R), (1, R, R), (30, R, R)]),
    "a_short_disagreement_while_moving_is_tolerated_when_armed": run([(0, R, R), (30, R, R), (5, R, M), (20, R, M), (5, M, M), (30, M, M)]),
    "a_disagreement_while_enabled_stops": run([(0, R, R), (30, R, R), (5, M, M), (30, M, M), (2, M, R), (2, M, M), (30, M, M)]),
    "a_long_disagreement_is_a_fault_left_only_by_a_release": run([(0, R, R), (30, R, R), (0, R, M), (60, R, M), (60, R, M), (5, M, M), (50, M, M), (5, R, R), (10, R, R), (15, R, R), (5, M, M), (30, M, M)]),
    "a_code_that_is_not_a_position_is_a_fault": run([(0, R, R), (30, R, R), (5, M, M), (30, M, M), (5, 0, 2), (5, M, M), (30, M, M), (5, 4, 4), (5, R, R), (30, R, R)]),
    "the_clock_wraps": [(0xFFFFFFF0, R, R), (0x10, R, R), (0x20, M, M), (0x30, M, M), (0x40, M, M)],
}


def render() -> str:
    cfg = e.load_config()
    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - tests/enabling_device_vectors.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        "/* Generated by tools/gen_enabling_vectors.py from tools/enabling_device.py. Do not edit: change the reference and run the tool. */",
        "#ifndef ENABLING_DEVICE_VECTORS_H",
        "#define ENABLING_DEVICE_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define ENABLING_VECTOR_DEBOUNCE_MS {cfg['debounce_ms']}u",
        f"#define ENABLING_VECTOR_DISCREPANCY_MS {cfg['discrepancy_ms']}u",
        "typedef struct { uint32_t t; uint8_t a, b; uint8_t state; uint8_t enabled; uint8_t stops; } enabling_step_t;",
        "typedef struct { const char *name; unsigned count; const enabling_step_t *steps; } enabling_scenario_t;",
        "",
    ]
    names = []
    for index, (name, steps) in enumerate(SCENARIOS.items()):
        device = e.EnablingDevice(cfg["debounce_ms"], cfg["discrepancy_ms"])
        lines.append(f"static const enabling_step_t enabling_steps_{index}[] = {{")
        for t, a, b in steps:
            enabled = device.update(t, a, b)
            lines.append(f"    {{{t}u, {a}, {b}, {device.state}, {int(enabled)}, {device.stops}}},")
        lines += ["};", ""]
        names.append(f'    {{"{name}", {len(steps)}u, enabling_steps_{index}}},')
    lines += [f"#define ENABLING_SCENARIO_COUNT {len(SCENARIOS)}", "static const enabling_scenario_t enabling_scenarios[ENABLING_SCENARIO_COUNT] = {"] + names + ["};", "", "#endif /* ENABLING_DEVICE_VECTORS_H */", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = HEADER_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n") if HEADER_PATH.is_file() else None
        if current != text:
            print("STALE: tests/enabling_device_vectors.h is not what the reference says (run tools/gen_enabling_vectors.py)")
            return 1
        return 0
    HEADER_PATH.write_bytes(text.encode("utf-8"))
    print("wrote tests/enabling_device_vectors.h")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
