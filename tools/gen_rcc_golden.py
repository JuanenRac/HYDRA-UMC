"""Writes tests/rcc_plan_golden.h: the writes of the clock set-up of the CM7 as tools/rcc_plan.py plans them for the default profile.

    python tools/gen_rcc_golden.py           write the file
    python tools/gen_rcc_golden.py --check   exit 1 when the file is not what the model produces

The waits for a ready flag are not in the file: the host test checks them with a double whose flags rise (or do not) by themselves. Evidence: simulator."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import platform_profile as pp
import rcc_plan as plan

HEADER_PATH = Path(__file__).resolve().parents[1] / "tests" / "rcc_plan_golden.h"
REGISTERS = {"CR": 0, "PLLCKSELR": 1, "PLLCFGR": 2, "PLL1DIVR": 3, "PLL2DIVR": 4, "D1CFGR": 5, "D2CFGR": 6, "D3CFGR": 7, "D2CCIP1R": 8, "CFGR": 9}
KINDS = {"flash_latency": 0, "write": 1, "set_bits": 2}


def render() -> str:
    steps = [s for s in plan.sequence(pp.profile("h757_target")) if s["op"] in KINDS]
    out = [
        "/* GENERATED by tools/gen_rcc_golden.py from tools/rcc_plan.py - do not edit by hand. */",
        "#ifndef HYDRA_RCC_PLAN_GOLDEN_H",
        "#define HYDRA_RCC_PLAN_GOLDEN_H",
        "",
        "/* kind: 0 flash latency (value: the bus clock in Hz), 1 register write, 2 set bits */",
        "typedef struct { int kind; int reg; unsigned long value; } RccGoldenStep;",
        "static const RccGoldenStep RCC_GOLDEN[] = {",
    ]
    for step in steps:
        reg = REGISTERS[step["reg"]] if "reg" in step else 0
        out.append(f'    {{{KINDS[step["op"]]}, {reg}, {step["value"]}UL}},')
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = HEADER_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n") if HEADER_PATH.is_file() else ""
        if current != text:
            print("RCC_GOLDEN=FAIL tests/rcc_plan_golden.h is not what the model produces: run tools/gen_rcc_golden.py", file=sys.stderr)
            return 1
        print("RCC_GOLDEN=PASS")
        return 0
    HEADER_PATH.write_bytes(text.encode("utf-8"))
    print(f"wrote {HEADER_PATH}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    raise SystemExit(main())
