"""Writes tests/task_watchdog_vectors.h: scenarios of the supervision of liveness run through the Python reference (tools/task_watchdog.py), so that the C twin
(src/mcu_stm32h757/CM4/task_watchdog.h) is held to the same states.

    python tools/gen_taskwd_vectors.py           write the header
    python tools/gen_taskwd_vectors.py --check   exit 1 when the header is not what the reference says

Each step is an event: a check-in of a task at a time, or an update at a time; after an update the header holds the state, the late mask, the trips and the answer. Evidence: simulator."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import task_watchdog as w  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
HEADER_PATH = ROOT / "tests" / "task_watchdog_vectors.h"

# a step is ("c", task, t) or ("u", t); the tasks are numbered as in config/task_watchdog.cfg: 0 control (20 ms), 1 bus (50 ms), 2 ui (500 ms, not mandatory)
CONTROL, BUS, UI = 0, 1, 2


def every(period, upto, tasks, start=0):
    steps = []
    for t in range(start, upto + 1, period):
        steps += [("c", task, t) for task in tasks] + [("u", t)]
    return steps


SCENARIOS = {
    "healthy_loop_never_trips": every(5, 400, (CONTROL, BUS, UI)),
    "control_hangs_and_the_refresh_stops": every(5, 100, (CONTROL, BUS, UI)) + [("u", t) for t in range(105, 200, 5)],
    "a_late_check_in_after_the_trip_does_not_clear_it": every(5, 60, (CONTROL, BUS, UI)) + [("u", 100), ("c", CONTROL, 101), ("u", 105), ("c", CONTROL, 106), ("u", 110)],
    "the_ui_is_late_only_degraded_and_recovers": every(5, 100, (CONTROL, BUS)) + [("c", UI, 100), ("u", 100)] + every(5, 700, (CONTROL, BUS), 105) + [("c", UI, 705), ("u", 705)],
    "bus_hangs": every(5, 100, (CONTROL, BUS, UI)) + every(5, 200, (CONTROL, UI), 105),
    "the_deadline_itself_is_not_late": [("u", 20), ("u", 21), ("c", CONTROL, 21), ("c", BUS, 21), ("u", 41), ("u", 42)],
    "a_check_in_of_a_number_that_is_no_task_is_ignored": [("c", 7, 5), ("c", 200, 5), ("u", 10), ("u", 25)],
    "the_clock_wraps": [("c", CONTROL, 0xFFFFFFF0), ("c", BUS, 0xFFFFFFF0), ("c", UI, 0xFFFFFFF0), ("u", 0xFFFFFFFA), ("c", CONTROL, 0xFFFFFFFE), ("u", 0x4), ("u", 0x20)],
}


def run(steps, cfg):
    dog = w.from_config(cfg)
    first = next(s[-1] for s in steps)
    dog.start(first)
    out = []
    for step in steps:
        if step[0] == "c":
            dog.check_in(step[1], step[2])
            out.append((0, step[2], step[1], 0, 0, 0, 0))
        else:
            refresh = dog.update(step[1])
            out.append((1, step[1], 0, dog.state, dog.late_mask, dog.trips, int(refresh)))
    return out, first


def render() -> str:
    cfg = w.load_config()
    lines = [
        "/* =============================================================================",
        " * HYDRA-UMC Firmware - tests/task_watchdog_vectors.h",
        " * Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        " * GPL-3.0-or-later - see LICENSE",
        " * ============================================================================= */",
        "/* Generated by tools/gen_taskwd_vectors.py from tools/task_watchdog.py. Do not edit: change the reference and run the tool. */",
        "#ifndef TASK_WATCHDOG_VECTORS_H",
        "#define TASK_WATCHDOG_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define TASKWD_VECTOR_TASKS {len(cfg['tasks'])}u",
        f"#define TASKWD_VECTOR_BOUND_MS {cfg['bound_ms']}u",
        "static const uint32_t taskwd_vector_deadline[TASKWD_VECTOR_TASKS] = {" + ", ".join(f"{d}u" for _, d, _ in cfg["tasks"]) + "};",
        "static const uint8_t taskwd_vector_mandatory[TASKWD_VECTOR_TASKS] = {" + ", ".join(str(m) for _, _, m in cfg["tasks"]) + "};",
        "typedef struct { uint8_t is_update; uint32_t t; uint8_t task; uint8_t state; uint16_t late; uint32_t trips; uint8_t refresh; } taskwd_step_t;",
        "typedef struct { const char *name; uint32_t start; unsigned count; const taskwd_step_t *steps; } taskwd_scenario_t;",
        "",
    ]
    names = []
    for index, (name, steps) in enumerate(SCENARIOS.items()):
        out, first = run(steps, cfg)
        lines.append(f"static const taskwd_step_t taskwd_steps_{index}[] = {{")
        for row in out:
            lines.append("    {" + f"{row[0]}, {row[1]}u, {row[2]}, {row[3]}, {row[4]}, {row[5]}u, {row[6]}" + "},")
        lines += ["};", ""]
        names.append(f'    {{"{name}", {first}u, {len(steps)}u, taskwd_steps_{index}}},')
    lines += [f"#define TASKWD_SCENARIO_COUNT {len(SCENARIOS)}", "static const taskwd_scenario_t taskwd_scenarios[TASKWD_SCENARIO_COUNT] = {"] + names + ["};", "", "#endif /* TASK_WATCHDOG_VECTORS_H */", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = HEADER_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n") if HEADER_PATH.is_file() else None
        if current != text:
            print("STALE: tests/task_watchdog_vectors.h is not what the reference says (run tools/gen_taskwd_vectors.py)")
            return 1
        return 0
    HEADER_PATH.write_bytes(text.encode("utf-8"))
    print("wrote tests/task_watchdog_vectors.h")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
